        Probability lives under density functions. For a discrete distribution, the probability of a single outcome is equal to the
        density at that point. The probability of multiple outcomes is equal to the sum of the densities at each point. For a
        continuous distribution, the probability at a single point is 0. The probability between two points is equal to the area
        under the curve between the two points.
